//! Access review: who held which Rancher permission at a point in time, who granted it and
//! when, and what changed between two dates.
//!
//! Rancher keeps no computed "effective permissions" anywhere, and bindings do not record
//! who created them. Both come from what Audit Loupe already stores: versions of the
//! permission objects on the Rancher cluster (any past state can be rebuilt), and the audit
//! records matched to those versions (who created or deleted a binding).
//!
//! Group-based grants are only as current as Rancher's own copy of a user's groups
//! (UserAttribute), refreshed at login, hourly on use, and daily; SAML and generic OIDC only
//! at login. The result says so rather than presenting it as exact.

use serde::Serialize;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};

/// One stored object as it was at the requested time.
#[derive(Debug, Clone)]
pub struct Obj {
    pub resource: String,
    pub namespace: String,
    pub name: String,
    pub body: Value,
    /// When Audit Loupe first saw this object (this UID).
    pub first_seen_ms: i64,
    /// The first version was the baseline: it existed before tracking started.
    pub before_tracking: bool,
    /// Who created it, from the audit record matched to its first version.
    pub created_by: Option<String>,
    pub created_by_inferred: bool,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct Grant {
    pub binding_kind: String,
    pub binding_namespace: String,
    pub binding_name: String,
    /// "global", "cluster" or "project".
    pub scope: String,
    pub cluster: String,
    pub project: String,
    pub role: String,
    pub role_display: String,
    /// "user" or "group".
    pub subject_kind: String,
    /// User ID, or group principal.
    pub subject: String,
    /// Set when a user holds this through one of their groups.
    pub via_group: Option<String>,
    pub granted_ms: i64,
    pub before_tracking: bool,
    pub granted_by: Option<String>,
    /// The grantor was matched by time and type only (no exact audit match).
    pub granted_by_inferred: bool,
    /// Generated by Rancher from a GlobalRole's inheritedClusterRoles.
    pub derived: bool,
    /// Created by Rancher itself (creator bindings, new users' default roles).
    pub automatic: bool,
    /// Rules after following RoleTemplate inheritance.
    pub rules: Vec<Value>,
    /// Role templates whose rules live in a ClusterRole of the same name in each cluster.
    pub external_roles: Vec<String>,
    /// Some rule allows every verb on every resource.
    pub admin_like: bool,
}

#[derive(Debug, Clone, Serialize)]
pub struct UserAccess {
    pub user_id: String,
    pub display_name: String,
    pub principal_ids: Vec<String>,
    pub groups: Vec<String>,
    /// When Audit Loupe last saw the group list change (Rancher refreshes it on its own schedule).
    pub groups_seen_ms: Option<i64>,
    pub grants: Vec<Grant>,
}

#[derive(Debug, Clone, Serialize)]
pub struct Snapshot {
    pub at_ms: i64,
    pub users: Vec<UserAccess>,
    /// Bindings to groups, whoever is in them.
    pub group_grants: Vec<Grant>,
    pub note: &'static str,
}

pub const GROUP_NOTE: &str = "group-based grants follow Rancher's last refresh of each user's groups (login, hourly on use, daily; SAML and generic OIDC only at login)";

fn s<'a>(v: &'a Value, p: &str) -> &'a str {
    v.pointer(p).and_then(Value::as_str).unwrap_or("")
}

fn strings(v: &Value, p: &str) -> Vec<String> {
    v.pointer(p).and_then(Value::as_array).map(|a| a.iter().filter_map(|x| x.as_str().map(String::from)).collect()).unwrap_or_default()
}

/// Group principals of a user from their UserAttribute (all providers).
pub fn groups_of(user_attribute: &Value) -> Vec<String> {
    let mut out = BTreeSet::new();
    for key in ["GroupPrincipals", "groupPrincipals"] {
        if let Some(m) = user_attribute.get(key).and_then(Value::as_object) {
            for list in m.values() {
                for p in list.get("items").or_else(|| list.get("Items")).and_then(Value::as_array).into_iter().flatten() {
                    let name = p.pointer("/metadata/name").and_then(Value::as_str).unwrap_or("");
                    if !name.is_empty() {
                        out.insert(name.to_string());
                    }
                }
            }
        }
    }
    out.into_iter().collect()
}

/// Follow RoleTemplate inheritance; external templates contribute a ClusterRole name instead
/// of rules (their rules live in each cluster).
fn expand(name: &str, templates: &HashMap<String, Value>, seen: &mut HashSet<String>, rules: &mut Vec<Value>, external: &mut Vec<String>) {
    if !seen.insert(name.to_string()) {
        return;
    }
    let Some(t) = templates.get(name) else { return };
    if t.get("external").and_then(Value::as_bool).unwrap_or(false) {
        match t.get("externalRules").and_then(Value::as_array) {
            Some(r) if !r.is_empty() => rules.extend(r.iter().cloned()),
            _ => external.push(name.to_string()),
        }
    } else if let Some(r) = t.get("rules").and_then(Value::as_array) {
        rules.extend(r.iter().cloned());
    }
    for child in strings(t, "/roleTemplateNames") {
        expand(&child, templates, seen, rules, external);
    }
}

fn admin_like(rules: &[Value]) -> bool {
    rules.iter().any(|r| {
        let has = |k: &str| r.get(k).and_then(Value::as_array).is_some_and(|a| a.iter().any(|x| x == "*"));
        has("verbs") && has("resources")
    })
}

fn display(v: &Value, fallback: &str) -> String {
    let d = s(v, "/displayName");
    if d.is_empty() { fallback.to_string() } else { d.to_string() }
}

/// Every grant in the snapshot, one per binding.
pub fn grants(objs: &[Obj]) -> Vec<Grant> {
    let templates: HashMap<String, Value> = objs.iter().filter(|o| o.resource == "roletemplates").map(|o| (o.name.clone(), o.body.clone())).collect();
    let globals: HashMap<String, Value> = objs.iter().filter(|o| o.resource == "globalroles").map(|o| (o.name.clone(), o.body.clone())).collect();
    let mut out = Vec::new();
    for o in objs {
        let b = &o.body;
        let (kind, scope) = match o.resource.as_str() {
            "globalrolebindings" => ("GlobalRoleBinding", "global"),
            "clusterroletemplatebindings" => ("ClusterRoleTemplateBinding", "cluster"),
            "projectroletemplatebindings" => ("ProjectRoleTemplateBinding", "project"),
            _ => continue,
        };
        let (role, role_display, mut rules, mut external) = if kind == "GlobalRoleBinding" {
            let r = s(b, "/globalRoleName").to_string();
            let g = globals.get(&r).cloned().unwrap_or(Value::Null);
            let mut ext = vec![];
            // Roles a GlobalRole grants in every downstream cluster.
            for t in strings(&g, "/inheritedClusterRoles") {
                let mut seen = HashSet::new();
                let mut inherited = vec![];
                expand(&t, &templates, &mut seen, &mut inherited, &mut ext);
                if !inherited.is_empty() {
                    ext.push(format!("{t} (every cluster)"));
                }
            }
            (r.clone(), display(&g, &r), g.get("rules").and_then(Value::as_array).cloned().unwrap_or_default(), ext)
        } else {
            let r = s(b, "/roleTemplateName").to_string();
            let mut rules = vec![];
            let mut ext = vec![];
            expand(&r, &templates, &mut HashSet::new(), &mut rules, &mut ext);
            let disp = templates.get(&r).map(|t| display(t, &r)).unwrap_or_else(|| r.clone());
            (r, disp, rules, ext)
        };
        rules.dedup();
        external.dedup();
        let (cluster, project) = match scope {
            "cluster" => (non_empty(s(b, "/clusterName"), &o.namespace), String::new()),
            "project" => {
                let pn = s(b, "/projectName");
                match pn.split_once(':') {
                    Some((c, p)) => (c.to_string(), p.to_string()),
                    None => (String::new(), pn.to_string()),
                }
            }
            _ => (String::new(), String::new()),
        };
        let user = non_empty(s(b, "/userName"), s(b, "/userPrincipalName"));
        let group = non_empty(s(b, "/groupPrincipalName"), s(b, "/groupName"));
        let (subject_kind, subject) = if !user.is_empty() { ("user", user) } else if !group.is_empty() { ("group", group) } else { continue };
        let derived = b.pointer("/metadata/labels/authz.management.cattle.io~1grb-owner").is_some();
        let automatic = b.pointer("/metadata/annotations/authz.management.cattle.io~1creator-owner-binding").is_some()
            || o.name.starts_with("creator-")
            || (kind == "GlobalRoleBinding" && o.name.starts_with("grb-") && o.created_by.is_none());
        out.push(Grant {
            binding_kind: kind.into(),
            binding_namespace: o.namespace.clone(),
            binding_name: o.name.clone(),
            scope: scope.into(),
            cluster,
            project,
            role,
            role_display,
            subject_kind: subject_kind.into(),
            subject,
            via_group: None,
            granted_ms: o.first_seen_ms,
            before_tracking: o.before_tracking,
            granted_by: o.created_by.clone(),
            granted_by_inferred: o.created_by_inferred,
            derived,
            automatic,
            admin_like: admin_like(&rules),
            rules,
            external_roles: external,
        });
    }
    out.sort_by(|a, b| (&a.subject, &a.scope, &a.cluster, &a.project, &a.role).cmp(&(&b.subject, &b.scope, &b.cluster, &b.project, &b.role)));
    out
}

fn non_empty(a: &str, b: &str) -> String {
    if a.is_empty() { b.to_string() } else { a.to_string() }
}

/// Grants per user (direct and through groups) plus group grants, from one snapshot.
/// `users`: (user id, display name, principal ids, group list, groups last seen).
pub fn snapshot(at_ms: i64, objs: &[Obj], users: Vec<(String, String, Vec<String>, Vec<String>, Option<i64>)>) -> Snapshot {
    let all = grants(objs);
    let group_grants: Vec<Grant> = all.iter().filter(|g| g.subject_kind == "group").cloned().collect();
    let mut out = Vec::new();
    for (id, name, principals, groups, groups_seen) in users {
        let mut mine: Vec<Grant> = all
            .iter()
            .filter(|g| g.subject_kind == "user" && (g.subject == id || principals.contains(&g.subject)))
            .cloned()
            .collect();
        for g in &group_grants {
            if groups.contains(&g.subject) {
                mine.push(Grant { via_group: Some(g.subject.clone()), ..g.clone() });
            }
        }
        out.push(UserAccess { user_id: id, display_name: name, principal_ids: principals, groups, groups_seen_ms: groups_seen, grants: mine });
    }
    out.sort_by(|a, b| a.display_name.cmp(&b.display_name));
    Snapshot { at_ms, users: out, group_grants, note: GROUP_NOTE }
}

#[derive(Debug, Clone, Serialize)]
pub struct Change {
    /// "added" or "removed".
    pub change: &'static str,
    pub grant: Grant,
    pub at_ms: Option<i64>,
    pub by: Option<String>,
    /// "rancher_cleanup" when Rancher removed it after deleting the user; "rancher_sync" for
    /// built-in role changes Rancher made on its own.
    pub reason: Option<&'static str>,
}

/// Bindings added or removed between two snapshots, keyed by binding.
pub fn diff(before: &[Grant], after: &[Grant]) -> (Vec<Grant>, Vec<Grant>) {
    let key = |g: &Grant| (g.binding_kind.clone(), g.binding_namespace.clone(), g.binding_name.clone());
    let b: BTreeMap<_, _> = before.iter().map(|g| (key(g), g)).collect();
    let a: BTreeMap<_, _> = after.iter().map(|g| (key(g), g)).collect();
    let added = a.iter().filter(|(k, _)| !b.contains_key(*k)).map(|(_, g)| (*g).clone()).collect();
    let removed = b.iter().filter(|(k, _)| !a.contains_key(*k)).map(|(_, g)| (*g).clone()).collect();
    (added, removed)
}

/// CSV for auditors: one row per (person, permission).
pub fn to_csv(snap: &Snapshot) -> String {
    let esc = |v: &str| {
        if v.contains([',', '"', '\n']) { format!("\"{}\"", v.replace('"', "\"\"")) } else { v.to_string() }
    };
    let mut out = String::from("person,user_id,role,scope,cluster,project,obtained_via,granted_by,granted_at,before_tracking,derived_or_automatic,admin_like\n");
    for u in &snap.users {
        for g in &u.grants {
            let when = chrono::DateTime::from_timestamp_millis(g.granted_ms).map(|t| t.to_rfc3339()).unwrap_or_default();
            let via = g.via_group.as_deref().map(|x| format!("group {x}")).unwrap_or_else(|| "direct".into());
            let by = match (&g.granted_by, g.granted_by_inferred) {
                (Some(b), true) => format!("{b} (inferred)"),
                (Some(b), false) => b.clone(),
                (None, _) => String::new(),
            };
            let auto = if g.derived { "derived" } else if g.automatic { "automatic" } else { "" };
            let row = [
                u.display_name.as_str(), &u.user_id, &g.role_display, &g.scope, &g.cluster, &g.project, &via, &by, &when,
                if g.before_tracking { "yes" } else { "" }, auto, if g.admin_like { "yes" } else { "" },
            ];
            out.push_str(&row.iter().map(|v| esc(v)).collect::<Vec<_>>().join(","));
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn obj(resource: &str, ns: &str, name: &str, body: Value) -> Obj {
        Obj { resource: resource.into(), namespace: ns.into(), name: name.into(), body, first_seen_ms: 1000, before_tracking: false, created_by: Some("carol".into()), created_by_inferred: false }
    }

    fn world() -> Vec<Obj> {
        vec![
            obj("roletemplates", "", "project-member", json!({"displayName":"Project Member","rules":[{"apiGroups":[""],"resources":["pods"],"verbs":["get"]}],"roleTemplateNames":["view-secrets"]})),
            obj("roletemplates", "", "view-secrets", json!({"rules":[{"apiGroups":[""],"resources":["secrets"],"verbs":["get"]}]})),
            obj("roletemplates", "", "cluster-owner", json!({"rules":[{"apiGroups":["*"],"resources":["*"],"verbs":["*"]}]})),
            obj("roletemplates", "", "edit-ext", json!({"external":true})),
            obj("globalroles", "", "user", json!({"displayName":"Standard User","rules":[{"apiGroups":["management.cattle.io"],"resources":["clusters"],"verbs":["create"]}]})),
            obj("projectroletemplatebindings", "p-shop", "prtb-bob", json!({"projectName":"c-m-1:p-shop","roleTemplateName":"project-member","userName":"u-bob"})),
            obj("clusterroletemplatebindings", "c-m-1", "crtb-ops", json!({"clusterName":"c-m-1","roleTemplateName":"cluster-owner","groupPrincipalName":"openldap_group://cn=ops"})),
            obj("clusterroletemplatebindings", "c-m-1", "crtb-ext", json!({"clusterName":"c-m-1","roleTemplateName":"edit-ext","userPrincipalName":"openldap_user://uid=alice"})),
            obj("globalrolebindings", "", "grb-abc", json!({"globalRoleName":"user","userName":"u-bob"})),
        ]
    }

    #[test]
    fn inheritance_groups_and_principals() {
        let snap = snapshot(2000, &world(), vec![
            ("u-bob".into(), "bob".into(), vec!["openldap_user://uid=bob".into()], vec![], None),
            ("u-alice".into(), "alice".into(), vec!["openldap_user://uid=alice".into()], vec!["openldap_group://cn=ops".into()], Some(1500)),
        ]);
        let alice = &snap.users[0];
        assert_eq!(alice.display_name, "alice");
        // Through the ops group: cluster owner, admin-like.
        let via_group = alice.grants.iter().find(|g| g.via_group.is_some()).unwrap();
        assert!(via_group.admin_like && via_group.role == "cluster-owner");
        // Bound by principal rather than user ID; external role rules are not expanded.
        let ext = alice.grants.iter().find(|g| g.role == "edit-ext").unwrap();
        assert_eq!(ext.external_roles, vec!["edit-ext".to_string()]);
        let bob = &snap.users[1];
        let prtb = bob.grants.iter().find(|g| g.scope == "project").unwrap();
        assert_eq!((prtb.cluster.as_str(), prtb.project.as_str(), prtb.role_display.as_str()), ("c-m-1", "p-shop", "Project Member"));
        assert_eq!(prtb.rules.len(), 2, "member rules plus inherited view-secrets");
        assert_eq!(snap.group_grants.len(), 1);
    }

    #[test]
    fn diff_and_csv() {
        let before = grants(&world());
        let mut later = world();
        later.retain(|o| o.name != "prtb-bob");
        later.push(obj("clusterroletemplatebindings", "c-m-1", "crtb-dave", json!({"clusterName":"c-m-1","roleTemplateName":"cluster-owner","userName":"u-dave"})));
        let (added, removed) = diff(&before, &grants(&later));
        assert_eq!((added[0].binding_name.as_str(), removed[0].binding_name.as_str()), ("crtb-dave", "prtb-bob"));
        let snap = snapshot(2000, &world(), vec![("u-bob".into(), "bob, jr".into(), vec![], vec![], None)]);
        let csv = to_csv(&snap);
        assert!(csv.lines().count() == 3, "{csv}");
        assert!(csv.contains("\"bob, jr\",u-bob,Project Member,project,c-m-1,p-shop,direct,carol"), "{csv}");
    }

    #[test]
    fn groups_from_user_attribute() {
        let ua = json!({"GroupPrincipals":{"openldap":{"items":[{"metadata":{"name":"openldap_group://cn=ops"}},{"metadata":{"name":"openldap_group://cn=dev"}}]}}});
        assert_eq!(groups_of(&ua), vec!["openldap_group://cn=dev".to_string(), "openldap_group://cn=ops".to_string()]);
    }
}
